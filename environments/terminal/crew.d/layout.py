"""`crew layout` prints a crew's resolved home-level layout and, with --write, its one-command start wrappers (#1178).

Usage: crew layout --project FILE [--org-profile FILE] [--write] [--owner-cmd CMD]

The layout is the profile's [paths] after the root resolver: with paths.root set (a set CREW_ROOT overrides it),
every relative state_dir, worktree_root, live_dir, eng_crew and checkout resolves under that one root, so a later
move of the whole layout changes one value. Rows: root, home (the profile's directory: the coordinator and leads
start there), checkout (paths.checkout, else home), state (the project's state directory), worktree_root, live_dir,
eng_crew and the CLI the wrappers run.

--write writes two POSIX sh wrappers and prints each path: `<home>/start` runs `crew up` for this profile from any
cwd, and `<checkout>/.crew/start-owner` starts the owner's session (`--owner-cmd`, default `claude`) in the checkout.
Paths are absolute and shell-quoted, so rerun --write after the layout moves. A wrapper file that exists without the
generated marker line is refused (exit 1) and left as it is. Nothing is written under ~/.claude or any other
user-level config.
"""
import os
import shlex
from crew_shared import checkout, CREW_BIN, profile

MARKER = "# Generated by crew layout --write (#1178); rerun it after the layout moves."


def register(sub):
    p = sub.add_parser("layout")
    p.add_argument("--project", required=True)
    p.add_argument("--org-profile")
    p.add_argument("--write", action="store_true", help="write <home>/start and <checkout>/.crew/start-owner")
    p.add_argument("--owner-cmd", default="claude", help="the owner session's command for start-owner")


def rows(values, project, state):
    home = os.path.dirname(os.path.abspath(project))
    cli = os.path.join(values["paths.eng_crew"], "scripts", "crew") if values.get("paths.eng_crew") else CREW_BIN
    return {"root": values.get("paths.root", ""), "home": home, "checkout": checkout(values, project), "state": state,
            "worktree_root": os.path.abspath(values["paths.worktree_root"]),
            "live_dir": os.path.abspath(values["paths.live_dir"]) if values.get("paths.live_dir") else "",
            "eng_crew": values.get("paths.eng_crew", ""), "cli": cli}


def wrappers(layout, project, owner_cmd):
    start = "#!/bin/sh\n%s\nexec %s up --project %s \"$@\"\n" % (
        MARKER, shlex.quote(layout["cli"]), shlex.quote(os.path.abspath(project)))
    owner = "#!/bin/sh\n%s\ncd %s || exit 1\nexec %s \"$@\"\n" % (
        MARKER, shlex.quote(layout["checkout"]), shlex.join(shlex.split(owner_cmd)))
    return {os.path.join(layout["home"], "start"): start,
            os.path.join(layout["checkout"], ".crew", "start-owner"): owner}


def run(args):
    values, _, state = profile(args, "worktree_root")
    layout = rows(values, args.project, state)
    for key, value in layout.items():
        print("%-13s %s" % (key, value or "(unset)"))
    if not args.write:
        return 0
    files = wrappers(layout, args.project, args.owner_cmd)
    refused = []
    for path in files:
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                if MARKER not in f.read().splitlines():
                    refused.append(path)
    if refused:
        print("crew: refusing layout --write: not generated by crew layout: %s" % ", ".join(refused))
        return 1
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
        os.chmod(path, 0o755)
        print("wrote %s" % path)
    return 0
